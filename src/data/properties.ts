function makeHistory(
  basePrice: number,
  months: string[]
): { month: string; price: number }[] {
  let current = basePrice;
  return months.map((month) => {
    const variance = (Math.random() * 0.1 - 0.05) * current;
    current = Math.round(current + variance);
    return { month, price: current };
  });
}

